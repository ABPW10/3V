function CalculateSolarTermsNewton(fn, jd,  angle)
 {
     
 
     JD1 = jd;
     do
     {
         JD0 = JD1;
         stDegree = fn(JD0) - angle;
         stDegreep = (fn(JD0 + 0.000005)
                       - fn(JD0 - 0.000005)) / 0.00001;
         JD1 = JD0 - stDegree / stDegreep;
     }while((Math.abs(JD1 - JD0) > 0.0000001));
 
     return JD1;
 }

function GetSunEclipticLongitudeECNegative180To180(jd){
  originalAng=GetSunEclipticLongitudeEC(jd)
  return originalAng-(originalAng>=180?360:0)
}

function calculateSolarTerm(jd, backward=false){
  ecliptic=GetSunEclipticLongitudeEC(jd);
  nextAngle=(backward?Math.floor:Math.ceil)(ecliptic/15.0)%24*15;
  return CalculateSolarTermsNewton(nextAngle>=270||nextAngle<90?GetSunEclipticLongitudeECNegative180To180:GetSunEclipticLongitudeEC,jd,nextAngle-(nextAngle>=270?360:0))
}