function AdjustSunEclipticLongitudeEC( dt,  longitude,  latitude)

{

     T = dt * 10; //T是儒略世纪数



     dbLdash = longitude - 1.397 * T - 0.00031 * T * T;



    // 转换为弧度

    dbLdash *= Math.PI/180.0;



    return (-0.09033 + 0.03916 * (Math.cos(dbLdash) + Math.sin(dbLdash)) * Math.tan(latitude * Math.PI/180.0)) / 3600.0;

}
function CalcSunEarthRadius( dt)

{

     R0 = CalcPeriodicTerm(Earth_R0, Earth_R0.length, dt);

     R1 = CalcPeriodicTerm(Earth_R1, Earth_R1.length, dt);

     R2 = CalcPeriodicTerm(Earth_R2, Earth_R2.length, dt);

     R3 = CalcPeriodicTerm(Earth_R3, Earth_R3.length, dt);

     R4 = CalcPeriodicTerm(Earth_R4, Earth_R4.length, dt);



     R = (((((R4 * dt) + R3) * dt + R2) * dt + R1) * dt + R0) / 100000000.0;



    return R;

}
