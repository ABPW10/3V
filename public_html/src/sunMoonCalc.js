function GetMoonEclipticLongitudeEC( dbJD)
{
  
  dt = (dbJD - 2451545) / 36525.0; /*儒略世纪数*/

 const [Lp,D,M,Mp,F,E]=GetMoonEclipticParameter(dt);

 /*计算月球地心黄经周期项*/
  EI = CalcMoonECLongitudePeriodicTbl(D, M, Mp, F, E);

 /*修正金星,木星以及地球扁率摄动*/
 EI += CalcMoonLongitudePerturbation(dt, Lp, F);

 /*计算月球地心黄经*/
  longitude = Lp + EI / 1000000.0;

 /*计算天体章动干扰*/
 longitude += CalcEarthLongitudeNutation(dt / 10.0);

 longitude = (val360=longitude%360)+(val360>=0?0:360);
 return longitude;
}
function CalcMoonECLongitudePeriodicTbl( D,  M,  Mp,  F,  E)
{
  EI = 0.0 ;

 for( i = 0; i < LongitudeRadius.length; i++)
 {
  sita = LongitudeRadius[i][0] * D + LongitudeRadius[i][1] * M + LongitudeRadius[i][2] * Mp + LongitudeRadius[i][3] * F;
 sita *= Math.PI/180.0;
 EI += (LongitudeRadius[i][4] * Math.sin(sita) * Math.pow(E, Math.abs(LongitudeRadius[i][1])));
 }

 return EI;
}
