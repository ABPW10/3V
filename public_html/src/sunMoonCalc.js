w -= 301*Math.sin(2*(w4 + w5) + w3)
w -= 158*Math.sin(w3 - 2*w1)
w += 123*Math.sin(2*(w4 + w5) - w3)
w += 63*Math.sin(2*w1)
w -= 59*Math.sin(2*(w1 + w4 + w5) - w3)
w -= 51*Math.sin(2*w4 + w3 + w5)
w += 48*Math.sin(2*(w3 - w1))
w += 46*Math.sin(2*(w4 - w3) + w5)
w -= 38*Math.sin(2*(w1 + w4 + w5))
w -= 31*Math.sin(2*(w3 + w4 + w5))
w += 29*Math.sin(2*w3)
w += 29*Math.sin(2*(w4 + w5 - w1) + w3)
w += 26*Math.sin(2*w4)
w -= 22*Math.sin(2*(w4 - w1))
w += 21*Math.sin(2*w4 + w5 - w3)
w += 16*Math.sin(2*w1 - w3 + w5)
w -= 15*Math.sin(w2 + w5)
w -= 13*Math.sin(w3 + w5 - 2*w1)
w -= 12*Math.sin(w5 - w2)
w += 11*Math.sin(2*(w3 - w4))
w -= 10*Math.sin(2*(w4 + w1) + w5 - w3)
w -= 8*Math.sin(2*(w4 + w1 + w5) + w3)
w += 7*Math.sin(2*(w4 + w5) + w2)
