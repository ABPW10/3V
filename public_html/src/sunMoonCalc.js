w += 6*Math.sin(2*w1 + w3)
w += 6*Math.sin(2*(w3 + w4 + w5 - w1))
w += 6*Math.sin(2*(w4 - w1) + w3 + w5)
w -= 6*Math.sin(2*(w1 - w3) + w5)
w -= 6*Math.sin(2*w1 + w5)
w += 5*Math.sin(w3 - w2)
