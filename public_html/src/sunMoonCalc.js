function GetEarthNutationParameter(dt)

{

    T = dt * 10; /*T是从J2000起算的儒略世纪数*/

    T2 = T * T;

    T3 = T2 * T;

    /*平距角（如月对地心的角距离）*/

    D = 297.85036 + 445267.111480 * T - 0.0019142 * T2 + T3 / 189474.0;

    /*太阳（地球）平近点角*/

    M = 357.52772 + 35999.050340 * T - 0.0001603 * T2 - T3 / 300000.0;

    /*月亮平近点角*/

    Mp = 134.96298 + 477198.867398 * T + 0.0086972 * T2 + T3 / 56250.0;

    /*月亮纬度参数*/

    F = 93.27191 + 483202.017538 * T - 0.0036825 * T2 + T3 / 327270.0;

    /*黄道与月亮平轨道升交点黄经*/

    Omega = 125.04452 - 1934.136261 * T + 0.0020708 * T2 + T3 / 450000.0;

    return [D, M, Mp, F, Omega]
}


 function GetSunEclipticLongitudeEC(jde)

{

    dt = (jde - 2451545) / 365250.0; /*儒略千年数*/



    // 计算太阳的地心黄经

    longitude = CalcSunEclipticLongitudeEC(dt);



    // 计算太阳的地心黄纬

    latitude = CalcSunEclipticLatitudeEC(dt) * 3600.0;



    // 修正精度

    longitude += AdjustSunEclipticLongitudeEC(dt, longitude, latitude);



    // 修正天体章动

    longitude += CalcEarthLongitudeNutation(dt);



    // 修正光行差

    /*太阳地心黄经光行差修正项是: -20".4898/R*/

    longitude -= (20.4898 / CalcSunEarthRadius(dt)) / (3600.0);



    return longitude;

}
function CalcSunEclipticLongitudeEC(dt)

{

     L0 = CalcPeriodicTerm(Earth_L0, Earth_L0.length, dt);

     L1 = CalcPeriodicTerm(Earth_L1, Earth_L1.length, dt);

     L2 = CalcPeriodicTerm(Earth_L2, Earth_L2.length, dt);

     L3 = CalcPeriodicTerm(Earth_L3, Earth_L3.length, dt);

     L4 = CalcPeriodicTerm(Earth_L4, Earth_L4.length, dt);

     L5 = CalcPeriodicTerm(Earth_L5, Earth_L5.length, dt);



     L = (((((L5 * dt + L4) * dt + L3) * dt + L2) * dt + L1) * dt + L0) / 100000000.0;



    /*地心黄经 = 日心黄经 + 180度*/

    return (val360=(L / (Math.PI/180.0) + 180.0)%360)+(val360<0?360:0);

}
function CalcPeriodicTerm(coff, count, dt)

{

    val = 0.0;



    for( i = 0; i < count; i++)

        val += (coff[i][0] * Math.cos((coff[i][1] + coff[i][2] * dt)));



    return val;

}
